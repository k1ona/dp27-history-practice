#!/usr/bin/env python3
"""Validate all bundled content.

Checks (BUILD_PLAN §8):
 1. JSON Schemas: sections.json, every section file, media credits.
 2. Minimum quantities per section.
 3. The constructed-material label on every item, question, model and source set.
 4. Timeframe consistency (timelines, chronology items, recall sheets, question timeframes).
 5. Every image has a credit, a licence and a file within the size limits.
 6. No banned words in student-facing text.
 7. Every fact id used has a row in content/_verification/<sectionId>.md.
 8. Extras: unique ids, cross-links, essay mix, Paper 1 visual rotation.

Usage:
  python scripts/validate_content.py           # content checks
  python scripts/validate_content.py --repo    # also scan repository files and commit messages for attribution words
"""
import argparse
import json
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

from jsonschema import Draft202012Validator
from referencing import Registry, Resource

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
LABEL = "Teacher-constructed practice material. Not an IB publication."
BANNED = re.compile(r"\b(ai|claude|chatgpt|generated)\b", re.IGNORECASE)
REPO_BANNED = re.compile(r"\b(claude|chatgpt|anthropic|openai|co-authored-by|ai-generated|generated by)\b", re.IGNORECASE)
VISUAL_TYPES = {"photograph", "cartoon", "poster", "painting", "map", "graph", "table", "diagram"}
MIN = {
    "P2P3": {"retrieval": 20, "drills": 10, "essayQuestions": 6},
    "P1": {"retrieval": 20, "drills": 15, "sourceSets": 4},
}
P1_DRILL_TYPES = {"p1_point_harvest", "p1_purpose", "p1_value_limitation", "p1_pair_statements"}


class Report:
    def __init__(self):
        self.errors, self.warnings, self.lines = [], [], []

    def check(self, name, errs, detail=""):
        status = "PASS" if not errs else "FAIL"
        self.lines.append(f"[{status}] {name}{(' · ' + detail) if detail else ''}")
        for e in errs:
            self.lines.append(f"    ERROR {e}")
        self.errors.extend(errs)

    def warn(self, msg):
        self.warnings.append(msg)


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def registry():
    reg = Registry()
    schemas = {}
    for p in sorted((CONTENT / "schema").glob("*.json")):
        s = load(p)
        Draft202012Validator.check_schema(s)
        schemas[p.name] = s
        reg = reg.with_resource(s["$id"], Resource.from_contents(s))
    return reg, schemas


def schema_errors(schema, reg, data, label):
    v = Draft202012Validator(schema, registry=reg)
    out = []
    for e in sorted(v.iter_errors(data), key=lambda e: list(e.absolute_path)):
        path = "/".join(str(x) for x in e.absolute_path)
        out.append(f"{label}: /{path}: {e.message[:300]}")
    return out


def walk_strings(obj, path=""):
    if isinstance(obj, str):
        yield path, obj
    elif isinstance(obj, dict):
        for k, v in obj.items():
            yield from walk_strings(v, f"{path}/{k}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            yield from walk_strings(v, f"{path}/{i}")


def fact_refs(obj):
    refs = set()
    for _, s in walk_strings(obj):
        if re.fullmatch(r"F-[A-Z0-9-]+-\d{2,3}", s):
            refs.add(s)
    return refs


def media_refs(obj):
    return {s for _, s in walk_strings(obj) if re.fullmatch(r"M-[a-z0-9-]+", s)}


def all_items(sec):
    items = list(sec.get("retrieval", [])) + list(sec.get("drills", []))
    for c in sec["context"]["chunks"]:
        items += c["checkpoint"]
    return items


def in_range(y, tf):
    return tf[0] <= y <= tf[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", action="store_true", help="also scan repository files and commit messages")
    args = ap.parse_args()
    r = Report()
    reg, schemas = registry()
    r.check("Schemas are valid JSON Schema (draft 2020-12)", [], f"{len(schemas)} schemas")

    smap = load(CONTENT / "sections.json")
    credits_path = CONTENT / "_media" / "credits.json"
    credits = load(credits_path) if credits_path.exists() else {"schema": "dp27.media.v1", "media": []}
    section_files = sorted((CONTENT / "sections").glob("*.json"))
    sections = {p.stem: load(p) for p in section_files}
    records = {s["sectionId"]: s for s in smap["sections"]}

    # 1. Schemas
    errs = schema_errors(schemas["sections.schema.json"], reg, smap, "sections.json")
    errs += schema_errors(schemas["media-credits.schema.json"], reg, credits, "credits.json")
    for sid, sec in sections.items():
        errs += schema_errors(schemas["section.schema.json"], reg, sec, f"sections/{sid}.json")
        if sec.get("sectionId") != sid:
            errs.append(f"sections/{sid}.json: sectionId '{sec.get('sectionId')}' does not match the file name")
        if sid not in records:
            errs.append(f"sections/{sid}.json: no record in sections.json")
    r.check("1. JSON Schemas", errs, f"sections.json, credits.json and {len(sections)} section file(s)")

    # 2. Minimum quantities
    errs, detail = [], []
    for sid, sec in sections.items():
        rec = records.get(sid)
        if not rec:
            continue
        kind = "P1" if rec["papers"] == ["P1"] else "P2P3"
        counts = {k: len(sec.get(k, [])) for k in MIN[kind]}
        for k, n in MIN[kind].items():
            if counts[k] < n:
                errs.append(f"{sid}: {k} has {counts[k]}, minimum {n}")
        if kind == "P1":
            p1d = sum(1 for d in sec.get("drills", []) if d["type"] in P1_DRILL_TYPES)
            if p1d < MIN["P1"]["drills"]:
                errs.append(f"{sid}: {p1d} Paper 1 single-question drills (Q1/Q2/Q3 types), minimum 15")
        ncp = sum(len(c["checkpoint"]) for c in sec["context"]["chunks"])
        detail.append(f"{sid}: " + ", ".join(f"{k} {v}" for k, v in counts.items()) +
                      f", chunks {len(sec['context']['chunks'])}, checkpoint items {ncp}, evidence facts {len(sec['context']['evidenceBank'])}")
    r.check("2. Minimum quantities", errs, "; ".join(detail))

    # 3. Labels
    errs, n = [], 0
    for sid, sec in sections.items():
        for it in all_items(sec):
            n += 1
            if it.get("label") != LABEL:
                errs.append(f"{sid}: item {it['itemId']} lacks the label")
        for q in sec.get("essayQuestions", []):
            n += 1
            if q.get("label") != LABEL:
                errs.append(f"{sid}: question {q['questionId']} lacks the label")
        for s in sec.get("sourceSets", []):
            n += 1
            if s.get("label") != LABEL:
                errs.append(f"{sid}: source set {s['sourceSetId']} lacks the label")
    r.check("3. Constructed-material label", errs, f"{n} labelled objects")

    # 4. Timeframes
    errs = []
    for sid, sec in sections.items():
        rec = records.get(sid)
        if not rec:
            continue
        tf = rec["timeframe"]
        if tf[0] > tf[1]:
            errs.append(f"{sid}: timeframe start after end")
        ctx = sec["context"]
        for e in ctx["visuals"]["timeline"]["events"]:
            if not in_range(e["year"], tf):
                errs.append(f"{sid}: timeline event {e['year']} '{e['text']}' outside {tf}")
        for e in ctx["recallSheet"]["chronology"]:
            if not in_range(e["year"], tf):
                errs.append(f"{sid}: recall chronology {e['year']} outside {tf}")
        for it in all_items(sec):
            if it["type"] == "chronology":
                ys = [x["year"] for x in it["sequence"]]
                for y in ys:
                    if not in_range(y, tf):
                        errs.append(f"{sid}: {it['itemId']} chronology year {y} outside {tf}")
                keys = [(x["year"], x.get("month", 0)) for x in it["sequence"]]
                if len(set(keys)) != len(keys):
                    errs.append(f"{sid}: {it['itemId']} chronology has two events with the same date, so the order is ambiguous")
            if it["type"] == "in_timeframe" and "timeframe" in it and it["timeframe"][0] > it["timeframe"][1]:
                errs.append(f"{sid}: {it['itemId']} timeframe start after end")
        for q in sec.get("essayQuestions", []):
            qt = q["timeframe"]
            if qt[0] > qt[1] or not (in_range(qt[0], tf) and in_range(qt[1], tf)):
                errs.append(f"{sid}: {q['questionId']} timeframe {qt} not inside section timeframe {tf}")
            nums = re.findall(r"\b(1[89]\d\d|20[0-2]\d)\b", q["text"])
            if nums and [int(nums[0]), int(nums[-1])] != qt:
                errs.append(f"{sid}: {q['questionId']} years in the question text {nums} do not match its timeframe {qt}")
    r.check("4. Timeframe consistency", errs)

    # 5. Media
    errs = []
    by_id = {m["mediaId"]: m for m in credits["media"]}
    dup = [k for k, v in Counter(m["mediaId"] for m in credits["media"]).items() if v > 1]
    errs += [f"credits.json: duplicate mediaId {d}" for d in dup]
    try:
        from PIL import Image
    except ImportError:
        Image = None
    for m in credits["media"]:
        f = ROOT / m["file"]
        if not f.exists():
            errs.append(f"{m['mediaId']}: file {m['file']} missing")
            continue
        if not m.get("creditLine"):
            errs.append(f"{m['mediaId']}: no credit line")
        if m["kind"] == "archival" and not (m.get("licence") or {}).get("name"):
            errs.append(f"{m['mediaId']}: no licence")
        size = f.stat().st_size
        if size > 260 * 1024:
            errs.append(f"{m['mediaId']}: {size // 1024} KB exceeds the image limit")
        if Image is not None and f.suffix == ".webp":
            with Image.open(f) as im:
                if im.width > 1600:
                    errs.append(f"{m['mediaId']}: {im.width}px wide (max 1600)")
    used = set()
    for sid, sec in sections.items():
        for mid in media_refs(sec):
            used.add(mid)
            if mid not in by_id:
                errs.append(f"{sid}: media {mid} has no entry in credits.json")
            elif sid not in by_id[mid]["usedIn"]:
                errs.append(f"{sid}: media {mid} is used here but credits.json usedIn does not list {sid}")
    for mid in by_id:
        if mid not in used:
            r.warn(f"credits.json: {mid} is not used by any section")
    r.check("5. Media credits and licences", errs, f"{len(by_id)} credited file(s), {len(used)} used")

    # 6. Banned words
    errs = []
    targets = [("sections.json", smap), ("_markbands.json", load(CONTENT / "_markbands.json")), ("credits.json", credits)]
    targets += [(f"sections/{k}.json", v) for k, v in sections.items()]
    for name, obj in targets:
        for path, s in walk_strings(obj):
            m = BANNED.search(s)
            if m:
                errs.append(f"{name}{path}: banned word '{m.group(0)}'")
    for p in sorted((ROOT / "app").rglob("*")):
        if p.suffix in (".js", ".html", ".css", ".json", ".webmanifest"):
            for i, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
                m = BANNED.search(line)
                if m:
                    errs.append(f"{p.relative_to(ROOT)}:{i}: banned word '{m.group(0)}'")
    r.check("6. Banned words in student-facing text", errs, "content JSON and app/ (UI text, code and comments)")

    # 7. Verification entries
    errs, nfacts = [], 0
    for sid, sec in sections.items():
        log = CONTENT / "_verification" / f"{sid}.md"
        logged = set(re.findall(r"^\|\s*(F-[A-Z0-9-]+-\d{2,3})\s*\|", log.read_text(encoding="utf-8"), re.M)) if log.exists() else set()
        if not log.exists():
            errs.append(f"{sid}: no verification log at content/_verification/{sid}.md")
        rows = {}
        if log.exists():
            for line in log.read_text(encoding="utf-8").splitlines():
                mm = re.match(r"^\|\s*(F-[A-Z0-9-]+-\d{2,3})\s*\|(.*)\|\s*$", line)
                if mm:
                    rows[mm.group(1)] = [c.strip() for c in mm.group(2).split("|")]
        for fid, cells in rows.items():
            if len(cells) < 4 or not all(cells[:4]) or not re.search(r"\d{4}-\d{2}-\d{2}", cells[-1]):
                errs.append(f"{sid}: verification row {fid} needs claim, source, location and access date")
        refs = fact_refs(sec)
        nfacts += len(refs)
        for fid in sorted(refs - logged):
            errs.append(f"{sid}: fact {fid} is used but has no verification row")
        bank = {f["factId"] for f in sec["context"]["evidenceBank"]}
        for fid in sorted(bank - logged):
            errs.append(f"{sid}: evidence-bank fact {fid} has no verification row")
        for d in sec["context"].get("historiography", []):
            if d["historian"] not in (log.read_text(encoding="utf-8") if log.exists() else ""):
                errs.append(f"{sid}: historian {d['historian']} not in the verification log")
    r.check("7. Every fact has a verification entry", errs, f"{nfacts} fact ids referenced")

    # 8. Extras
    errs = []
    ids = Counter()
    for sid, sec in sections.items():
        for it in all_items(sec):
            ids[it["itemId"]] += 1
        for q in sec.get("essayQuestions", []):
            ids[q["questionId"]] += 1
        for s in sec.get("sourceSets", []):
            ids[s["sourceSetId"]] += 1
            for q in s["questions"]:
                ids[q["questionId"]] += 1
        for it in all_items(sec):
            if not it["itemId"].startswith(sid + "-"):
                errs.append(f"{sid}: item id {it['itemId']} does not start with the section id")
            for o in it.get("options", []):
                if len(o.get("explanation", "")) < 10:
                    errs.append(f"{sid}: {it['itemId']} option {o['id']} has no real explanation")
            if it["type"] in ("mcq", "which_argument", "spot_error", "pick_thesis", "upgrade_sentence", "strongest_counter",
                              "judgement_criterion", "p1_purpose", "p1_value_limitation", "in_timeframe"):
                nc = sum(1 for o in it["options"] if o["correct"])
                if nc != 1:
                    errs.append(f"{sid}: {it['itemId']} single-answer item has {nc} correct options")
        qs = sec.get("essayQuestions", [])
        if qs:
            want_paper = "P2" if sid.startswith("P2-") else "P3"
            for q in qs:
                if q["paper"] != want_paper:
                    errs.append(f"{sid}: {q['questionId']} has paper {q['paper']}, expected {want_paper} (the task timer and the register use this field)")
            terms = {q["commandTerm"] for q in qs}
            if len(terms) < 4:
                errs.append(f"{sid}: only {len(terms)} command terms (need 4)")
            nf = sum(1 for q in qs if {"named_factor", "proposition"} & set(q["features"]))
            if nf < 2:
                errs.append(f"{sid}: {nf} named-factor/proposition questions (need 2)")
            if not any("two_part" in q["features"] for q in qs):
                errs.append(f"{sid}: no two-part question")
            if not any({"comparative", "two_state", "two_region"} & set(q["features"]) for q in qs):
                r.warn(f"{sid}: no comparative question")
            for q in qs:
                if q.get("requiresTwoRegions") and "region" not in q["text"].lower():
                    errs.append(f"{sid}: {q['questionId']} needs two regions but the question text does not say so")
                if {"comparative", "two_state", "two_region"} & set(q["features"]) and "explicit_comparison" not in q["selfCheck"]:
                    errs.append(f"{sid}: {q['questionId']} is comparative but its self-check lacks explicit_comparison")
                if q["namedFactor"] and not any(a.get("isNamedFactor") for a in q["modelPlan"]["arguments"][:1]):
                    errs.append(f"{sid}: {q['questionId']} model plan does not put the named factor first")
        sets = sec.get("sourceSets", [])
        if sets:
            vis_types = []
            for s in sets:
                vis = [x["type"] for x in s["sources"] if x["type"] in VISUAL_TYPES]
                if not vis:
                    errs.append(f"{sid}: {s['sourceSetId']} has no visual source")
                vis_types.append(tuple(sorted(set(vis))))
                parts = sorted(q["part"] for q in s["questions"])
                if parts != ["p1q1a", "p1q1b", "p1q2", "p1q3", "p1q4"]:
                    errs.append(f"{sid}: {s['sourceSetId']} must have Q1(a), Q1(b), Q2, Q3 and Q4")
                marks = {q["part"]: q["marks"] for q in s["questions"]}
                if marks != {"p1q1a": 3, "p1q1b": 2, "p1q2": 4, "p1q3": 6, "p1q4": 9}:
                    errs.append(f"{sid}: {s['sourceSetId']} marks must be 3, 2, 4, 6, 9")
                for q in s["questions"]:
                    want = "band" if q["part"] in ("p1q3", "p1q4") else "points"
                    if q["model"]["type"] != want:
                        errs.append(f"{sid}: {q['questionId']} model should be {want}-based")
                letters = [x["letter"] for x in s["sources"]]
                if letters != ["A", "B", "C", "D"]:
                    errs.append(f"{sid}: {s['sourceSetId']} sources must be A–D in order")
            if len(set(vis_types)) < min(2, len(sets)):
                errs.append(f"{sid}: visual source types are not rotated across sets ({vis_types})")
    errs += [f"duplicate id {k}" for k, v in ids.items() if v > 1]
    sids = set(records)
    for x in smap["crossLinks"]:
        for s in x["sectionIds"]:
            if s not in sids:
                errs.append(f"crossLink {x['id']}: unknown section {s}")
    for sid, sec in sections.items():
        for f in sec["context"]["evidenceBank"]:
            for s in f.get("alsoWorksFor", []):
                if s not in sids:
                    errs.append(f"{sid}: {f['factId']} alsoWorksFor unknown section {s}")
    r.check("8. Ids, cross-links, essay mix, Paper 1 structure", errs)

    if args.repo:
        errs = []
        try:
            files = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=ROOT,
                                   capture_output=True, text=True, check=True).stdout.split()
        except Exception as e:
            files = []
            errs.append(f"git ls-files failed: {e}")
        for f in files:
            p = ROOT / f
            if f == "scripts/validate_content.py" or not p.is_file() or p.suffix in (".webp", ".png", ".jpg"):
                continue
            try:
                text = p.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                continue
            for i, line in enumerate(text.splitlines(), 1):
                m = REPO_BANNED.search(line) or BANNED.search(line)
                if m:
                    errs.append(f"{f}:{i}: '{m.group(0)}'")
        log = subprocess.run(["git", "log", "--format=%H%n%an <%ae>%n%B%n----"], cwd=ROOT, capture_output=True, text=True).stdout
        for line in log.splitlines():
            m = REPO_BANNED.search(line) or BANNED.search(line)
            if m:
                errs.append(f"commit message: '{line.strip()[:80]}'")
        r.check("R. Repository and commit messages free of attribution words", errs, f"{len(files)} file(s) scanned")

    print("DP27 content validation")
    print(f"sections.json: {len(records)} sections · content files: {len(sections)} ({', '.join(sections) or 'none'})")
    for line in r.lines:
        print(line)
    for w in r.warnings:
        print(f"WARNING {w}")
    print(f"Result: {len(r.errors)} error(s), {len(r.warnings)} warning(s)")
    return 1 if r.errors else 0


if __name__ == "__main__":
    sys.exit(main())
